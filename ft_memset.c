#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	size_t	i;
	char	*ptr;

	i = 0;
	while (i < n)
	{
		ptr = (char *)s;
		ptr[i] = c;
		i++;
	}
	return (s);
}
